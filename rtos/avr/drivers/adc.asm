.IFNDEF OS_DRV_ADC_INIT
.include "core/irq_set.asm"
;Биты флагов
.EQU _OS_DRV_ADC__FLAG_ENABLED						= 0x00
.EQU _OS_DRV_ADC__FLAG_BUSY							= 0x01

;-----------------------------------------------------------
OS_DRV_ADC_INIT:
;-----------------------------------------------------------
;Инициализируем ADC
;-----------------------------------------------------------
	MCALL OS_DISPATCHER_LOCK
	PUSH_A32

	LDI ACCUM_L,OS_IRQ_ADC									;Устанавливаем обработчик для прерывания ADC
   	LDS ACCUM_EL,_OS_STAT_POOL+_DRV_ADC__STAT_FIELD_CALLBACK+0x00
   	LDS ACCUM_EH,_OS_STAT_POOL+_DRV_ADC__STAT_FIELD_CALLBACK+0x01
   	MCALL OS_IRQ_SET

	_OS_POWER_ON PRADC

	LDS ACCUM_L,_OS_STAT_POOL+_DRV_ADC__STAT_FIELD_REF
	MCALL OS_DRV_ADC_SET_REFERENCE
	CLI
	LDS ACCUM_L,ADMUX
	LDS ACCUM_H,_OS_STAT_POOL+_DRV_ADC__STAT_FIELD_CHANNEL
	ANDI ACCUM_L,low(~((1<<MUX3)|(1<<MUX2)|(1<<MUX1)|(1<<MUX0)))
	OR ACCUM_L,ACCUM_H
	STS ADMUX,ACCUM_L
	SEI
	STS ADCSRB,C0x00

	LDI ACCUM_L,(1<<ADEN)
	LDS ACCUM_H,_OS_STAT_POOL+_DRV_ADC__STAT_FIELD_MODE
	CPI ACCUM_H,_DRV_ADC__MODE_SINGLE
	BREQ _OS_DRV_ADC__INIT_MODE_DONE
	CPI ACCUM_H,_DRV_ADC__MODE_FREE_RUNNING
	BRNE _OS_DRV_ADC_INIT__THROW_UNSUPPORTED_PARAM
	ORI ACCUM_L,(1<<ADATE)
_OS_DRV_ADC__INIT_MODE_DONE:

	LDI ACCUM_EL,0x00
	LDS ACCUM_H,_OS_STAT_POOL+_DRV_ADC__STAT_FIELD_PRESC
	CPI ACCUM_H,0x02
	BRNE PC+0x02
	LDI ACCUM_EL,(0<<ADPS2)|(0<<ADPS1)|(1<<ADPS0)
	CPI ACCUM_H,0x04
	BRNE PC+0x02
	LDI ACCUM_EL,(0<<ADPS2)|(1<<ADPS1)|(0<<ADPS0)
	CPI ACCUM_H,0x08
	BRNE PC+0x02
	LDI ACCUM_EL,(0<<ADPS2)|(1<<ADPS1)|(1<<ADPS0)
	CPI ACCUM_H,0x10
	BRNE PC+0x02
	LDI ACCUM_EL,(1<<ADPS2)|(0<<ADPS1)|(0<<ADPS0)
	CPI ACCUM_H,0x20
	BRNE PC+0x02
	LDI ACCUM_EL,(1<<ADPS2)|(0<<ADPS1)|(1<<ADPS0)
	CPI ACCUM_H,0x40
	BRNE PC+0x02
	LDI ACCUM_EL,(1<<ADPS2)|(1<<ADPS1)|(0<<ADPS0)
	CPI ACCUM_H,0x80
	BRNE PC+0x02
	LDI ACCUM_EL,(1<<ADPS2)|(1<<ADPS1)|(1<<ADPS0)

	CPI ACCUM_EL,0x00
	BREQ _OS_DRV_ADC_INIT__THROW_UNSUPPORTED_PARAM
	OR ACCUM_L,ACCUM_EL
	STS ADCSRA,ACCUM_L

	LDI ACCUM_L,(1<<_OS_DRV_ADC__FLAG_ENABLED)
	STS _OS_STAT_POOL+_DRV_ADC__STAT_FIELD_FLAGS,ACCUM_L

	POP_A32
	MCALL OS_DISPATCHER_UNLOCK
	RET
_OS_DRV_ADC_INIT__THROW_UNSUPPORTED_PARAM:
	POP_A32
	MCALL OS_DISPATCHER_UNLOCK
	LDI ACCUM_L,OS_DRIVER_EXCEPTION_ID
	LDI ACCUM_H,OSR_UNSUPPORTED_PARAM
	MJMP _J8BPROC_ETRACE_ADDFIRST__SET

;-----------------------------------------------------------
OS_DRV_ADC_SET_CHANNEL:
;-----------------------------------------------------------
;Задаем канал
;ACCUM_L-канал
;-----------------------------------------------------------
	CPI ACCUM_L,OS_ADC_CHANNELS_QNT
	BRCS _OS_DRV_ADC_SET_CHANNEL__CORRECT
	LDI ACCUM_L,OS_DRIVER_EXCEPTION_ID
	LDI ACCUM_H,OSR_UNSUPPORTED_PARAM
	MJMP _J8BPROC_ETRACE_ADDFIRST__SET
_OS_DRV_ADC_SET_CHANNEL__CORRECT:
	STS _OS_STAT_POOL+_DRV_ADC__STAT_FIELD_CHANNEL,ACCUM_L

	PUSH ACCUM_H
	CLI
	LDS ACCUM_H,ADMUX
	ANDI ACCUM_H,low(~((1<<MUX3)|(1<<MUX2)|(1<<MUX1)|(1<<MUX0)))
	OR ACCUM_H,ACCUM_L
	STS ADMUX,ACCUM_H
	SEI

	POP ACCUM_H
	RET

;-----------------------------------------------------------
OS_DRV_ADC_SET_REFERENCE:
;-----------------------------------------------------------
;Задаем опорное напряжение
;ACCUM_L-_DRV_ADC__REF_*
;-----------------------------------------------------------
	PUSH ACCUM_H

	CPI ACCUM_L,_DRV_ADC__REF_INTERNAL_VREF
	BRNE _OS_DRV_ADC_SET_REFERENCE__NO_INTERNAL_VREF
	LDI ACCUM_H,ADC_VREF_AREF
	RJMP _OS_DRV_ADC_SET_REFERENCE__CHECK_DONE
_OS_DRV_ADC_SET_REFERENCE__NO_INTERNAL_VREF:
	CPI ACCUM_L,_DRV_ADC__REF_EXTERNAL_AREF0
	BRNE _OS_DRV_ADC_SET_REFERENCE__NO_EXTERNAL_AREF0
	LDI ACCUM_H,ADC_VREF_AVCC
	RJMP _OS_DRV_ADC_SET_REFERENCE__CHECK_DONE
_OS_DRV_ADC_SET_REFERENCE__NO_EXTERNAL_AREF0:
.IFDEF ADC_VREF_1_1_CAP
	CPI ACCUM_L,_DRV_ADC__REF_INTERNAL_1_1V
	BRNE _OS_DRV_ADC_SET_REFERENCE__NO_INTERNAL
	LDI ACCUM_H,ADC_VREF_1_1_CAP
	RJMP _OS_DRV_ADC_SET_REFERENCE__CHECK_DONE
.ENDIF
.IFDEF ADC_VREF_2_56_CAP
	CPI ACCUM_L,_DRV_ADC__REF_INTERNAL_2_56V
	BRNE _OS_DRV_ADC_SET_REFERENCE__NO_INTERNAL
	LDI ACCUM_H,ADC_VREF_1_1_CAP
	RJMP _OS_DRV_ADC_SET_REFERENCE__CHECK_DONE
.ENDIF
_OS_DRV_ADC_SET_REFERENCE__NO_INTERNAL:
	RJMP _OS_DRV_ADC_SET_REFERENCE__THROW_UNSUPPORTED_PARAM
_OS_DRV_ADC_SET_REFERENCE__CHECK_DONE:
	STS _OS_STAT_POOL+_DRV_ADC__STAT_FIELD_REF,ACCUM_L

	CLI
	LDS ACCUM_L,ADMUX
	ANDI ACCUM_L,low(~((1<<REFS1)|(1<<REFS0)))
	OR ACCUM_L,ACCUM_H
	STS ADMUX,ACCUM_L
	SEI
	POP ACCUM_H
	RET

_OS_DRV_ADC_SET_REFERENCE__THROW_UNSUPPORTED_PARAM:
	POP ACCUM_H
	LDI ACCUM_L,OS_DRIVER_EXCEPTION_ID
	LDI ACCUM_H,OSR_UNSUPPORTED_PARAM
	MJMP _J8BPROC_ETRACE_ADDFIRST__SET

;-----------------------------------------------------------
OS_DRV_ADC_START:
;-----------------------------------------------------------
;Запускаем ADC
;-----------------------------------------------------------
   	PUSH ACCUM_L

	CLI
	LDS ACCUM_L,ADCSRA
	ORI ACCUM_L,(1<<ADEN)|(1<<ADSC)
	STS ADCSRA,ACCUM_L
	SEI

   	LDS ACCUM_L,_OS_STAT_POOL+_DRV_ADC__STAT_FIELD_CALLBACK+0x00
	CP ACCUM_L,C0x00
   	LDS ACCUM_L,_OS_STAT_POOL+_DRV_ADC__STAT_FIELD_CALLBACK+0x01
	CPC ACCUM_L,C0x00
	BREQ OS_DRV_ADC_START__SYNC_MODE
	POP ACCUM_L
	RET
OS_DRV_ADC_START__SYNC_MODE:
OS_DRV_ADC_START__LOOP:
	LDS ACCUM_L,ADCSRA
	SBRS ACCUM_L,ADIF
	RJMP OS_DRV_ADC_START__LOOP

	CLI
	LDS ACCUM_L,ADCSRA
	ORI ACCUM_L,(1<<ADIF)
	STS ADCSRA,ACCUM_L
	LDS ACCUM_L,ADCL
	STS _OS_STAT_POOL+_DRV_ADC__STAT_FIELD_RAWVALUE+0x00,ACCUM_L
	LDS ACCUM_L,ADCH
	STS _OS_STAT_POOL+_DRV_ADC__STAT_FIELD_RAWVALUE+0x01,ACCUM_L
	SEI

	POP ACCUM_L
	RET

;-----------------------------------------------------------
OS_DRV_ADC_SHUTDOWN:
;-----------------------------------------------------------
;Останавливаем и выключаем ADC
;-----------------------------------------------------------
	PUSH ACCUM_L

	CLI
	LDS ACCUM_L,ADCSRA
	ANDI ACCUM_L,low(~(1<<ADEN))
	STS ADCSRA,ACCUM_L
	SEI

	STS _OS_STAT_POOL+_DRV_ADC__STAT_FIELD_FLAGS,C0x00
	_OS_POWER_OFF PRADC

	POP ACCUM_L
	RET

;-----------------------------------------------------------
OS_DRV_ADC_INIT__IRQ_HANDLER:
;-----------------------------------------------------------
;Обработчик аппаратного прерывания
;-----------------------------------------------------------
	PUSH ACCUM_L

	LDS ACCUM_L,ADCL
	STS _OS_STAT_POOL+_DRV_ADC__STAT_FIELD_RAWVALUE+0x00,ACCUM_L
	LDS ACCUM_L,ADCH
	STS _OS_STAT_POOL+_DRV_ADC__STAT_FIELD_RAWVALUE+0x01,ACCUM_L
	LDS ACCUM_L,_OS_STAT_POOL+_DRV_ADC__STAT_FIELD_FLAGS
	ANDI ACCUM_L,low(~(1<<_OS_DRV_ADC__FLAG_BUSY))
	STS _OS_STAT_POOL+_DRV_ADC__STAT_FIELD_FLAGS,ACCUM_L

	POP ACCUM_L
	RET

.ENDIF
