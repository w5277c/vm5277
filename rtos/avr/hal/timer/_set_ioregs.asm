.IFNDEF _OS_HAL_TIMER_SET_IOREGS
;-----------------------------------------------------------
_OS_HAL_TIMER_SET_IOREGS:
;-----------------------------------------------------------
;Устанавливаем IO регистры аппаратного таймера
;IN: ACCUM_L/H-период, RESULT-CS значение,FLAGS-номер
;таймера
;OUT: флаг C-true-успешно, ACCUM_L-номер прерываний
;-----------------------------------------------------------
.IF OS_FT_TIMER == 0
	CPI FLAGS,0x00
	BRNE _OS_HAL_TIMER_SET_IOREGS__SUCCESS__CHECK_T1
;===TIMER0===ATMEGA48/88/168/328=ATMEGA328b=================
.IF CHIP_FAMILY==FAMILY_ATMEGAx8 || CHIP_FAMILY==FAMILY_ATTINYx313
	LDI ACCUM_EL,(1<<WGM01)
	STS TCCR0A,ACCUM_EL										;OUTPUT NORMAL OPERATIONS, CTC MODE
	STS TCCR0B,RESULT
	STS TCNT0,C0x00
	STS OCR0A,ACCUM_L
	LDI ACCUM_EL,(1<<OCF0A)
	STS TIFR0,ACCUM_EL
	LDI ACCUM_L,OS_IRQ_TIMER0_CMPA
	SEC
	RET
.ELIF CHIP_FAMILY==FAMILY_ATMEGA16
	ORI RESULT,(1<<WGM01)
	STS TCCR0,RESULT
	STS TCNT0,C0x00
	STS OCR0,ACCUM_L
	LDI ACCUM_EL,(1<<OCF0)
	STS TIFR,ACCUM_EL
	LDI ACCUM_L,OS_IRQ_TIMER0_CMPA
	SEC
   	RET
.ELSE
.ERROR "Unsupported chip family for timer0, id:", CHIP_FAMILY
.ENDIF
.ENDIF
_OS_HAL_TIMER_SET_IOREGS__SUCCESS__CHECK_T1:
.IF OS_TIMERS_QNT > 1
	CPI FLAGS,0x01
	BRNE _OS_HAL_TIMER_SET_IOREGS__SUCCESS__CHECK_T2
;===TIMER1===ATMEGA48/88/168/328=ATMEGA328b=================
.IF CHIP_FAMILY==FAMILY_ATMEGAx8 || CHIP_FAMILY==FAMILY_ATMEGA16 || CHIP_FAMILY==FAMILY_ATTINYx313
	STS TCCR1A,C0x00
	ORI RESULT,(1<<WGM12)
	STS TCCR1B,RESULT
.IFDEF TCCR1C
	STS TCCR1C,C0x00
.ENDIF
	STS TCNT1H,C0x00
	STS TCNT1L,C0x00
	STS OCR1AH,ACCUM_H
	STS OCR1AL,ACCUM_L
	LDI ACCUM_EL,(1<<OCF1A)
.IF CHIP_FAMILY==FAMILY_ATMEGAx8
	STS TIFR1,ACCUM_EL
.ELSE
	STS TIFR,ACCUM_EL
.ENDIF
	LDI ACCUM_L,OS_IRQ_TIMER1_CMPA
	SEC
   	RET
.ELSE
.ERROR "Unsupported chip family for timer1, id:", CHIP_FAMILY
.ENDIF
.ENDIF
_OS_HAL_TIMER_SET_IOREGS__SUCCESS__CHECK_T2:
.IF OS_TIMERS_QNT > 2
	CPI FLAGS,0x02
	BRNE _OS_HAL_TIMER_SET_IOREGS__SUCCESS__CHECK_T3
;===TIMER2===ATMEGA48/88/168/328=ATMEGA328b=================
.IF CHIP_FAMILY==FAMILY_ATMEGAx8
	LDI ACCUM_EL,(1<<WGM21)
	STS TCCR2A,ACCUM_EL										;OUTPUT NORMAL OPERATIONS, CTC MODE
	STS TCCR2B,RESULT
.IFDEF TCCR2C
	STS TCCR2C,C0x00
.ENDIF
	STS TCNT2,C0x00
	STS OCR2A,ACCUM_L
	LDI ACCUM_EL,(1<<OCF2A)
	STS TIFR2,ACCUM_EL
	LDI ACCUM_L,OS_IRQ_TIMER2_CMPA
	SEC
   	RET
.ELIF CHIP_FAMILY==FAMILY_ATMEGA16
	ORI RESULT,(1<<WGM21)
	STS TCCR2,RESULT
	STS TCNT2,C0x00
	STS OCR2,ACCUM_L
	LDI ACCUM_EL,(1<<OCF2)
	STS TIFR,ACCUM_EL
	LDI ACCUM_L,OS_IRQ_TIMER0_CMPA
	SEC
   	RET
.ELSE
.ERROR "Unsupported chip family for timer2, id:", CHIP_FAMILY
.ENDIF
.ENDIF
_OS_HAL_TIMER_SET_IOREGS__SUCCESS__CHECK_T3:
.IF OS_TIMERS_QNT > 3
	CPI FLAGS,0x03
	BRNE _OS_HAL_TIMER_SET_IOREGS__SUCCESS__CHECK_T4
;===TIMER3===ATMEGA328b=====================================
.IF CHIP_FAMILY==FAMILY_ATMEGAx8
	STS TCCR3A,C0x00
	ORI RESULT,(1<<WGM32)
	STS TCCR3B,RESULT
.IFDEF TCCR3C
	STS TCCR3C,C0x00
.ENDIF
	STS TCNT3,C0x00
	STS OCR3A,ACCUM_L
	LDI ACCUM_EL,(1<<OCF3A)
	STS TIFR3,ACCUM_EL
	LDI ACCUM_L,OS_IRQ_TIMER3_CMPA
	SEC
   	RET
.ELSE
.ERROR "Unsupported chip family for timer3, id:", CHIP_FAMILY
.ENDIF
.ENDIF
_OS_HAL_TIMER_SET_IOREGS__SUCCESS__CHECK_T4:
.IF OS_TIMERS_QNT > 4
	CPI FLAGS,0x04
	BRNE _OS_HAL_TIMER_SET_IOREGS__SUCCESS__CHECK_T5
;===TIMER4===ATMEGA328b=====================================
.IF CHIP_FAMILY==FAMILY_ATMEGAx8
	STS TCCR4A,C0x00
	ORI RESULT,(1<<WGM42)
	STS TCCR4B,RESULT
.IFDEF TCCR4C
	STS TCCR4C,C0x00
.ENDIF
	STS TCNT4,C0x00
	STS OCR4A,ACCUM_L
	LDI ACCUM_EL,(1<<OCF4A)
	STS TIFR4,ACCUM_EL
	LDI ACCUM_L,OS_IRQ_TIMER4_CMPA
	SEC
   	RET
.ELSE
.ERROR "Unsupported chip family for timer4, id:", CHIP_FAMILY
.ENDIF
.ENDIF
_OS_HAL_TIMER_SET_IOREGS__SUCCESS__CHECK_T5:
	CLC
	RET
.ENDIF